// Writes src/lib/commonPasswords.ts from SecLists' 10k-most-common.txt, the
// list of the most common passwords an exact match with which is never
// allowed. Run with `pnpm common:passwords [file]`: with a file it reads that
// copy, else it downloads the list at the pinned commit. The list is data,
// never code: each line goes into one JSON string.
import { readFileSync, writeFileSync } from 'node:fs';

const COMMIT = '913b327317496d062bcc7cace524aaad8a693be2';
const PATH = 'Passwords/Common-Credentials/10k-most-common.txt';
const URL_RAW = `https://raw.githubusercontent.com/danielmiessler/SecLists/${COMMIT}/${PATH}`;
const OUT = new URL('../src/lib/commonPasswords.ts', import.meta.url).pathname;

const file = process.argv[2];
const text = file ? readFileSync(file, 'utf8') : await (await fetch(URL_RAW)).text();
const lines = text.replace(/\r\n?/g, '\n').split('\n').filter((l) => l !== '');
if (lines.length < 9000 || new Set(lines).size !== lines.length) throw new Error(`unexpected list: ${lines.length} lines`);

writeFileSync(
  OUT,
  `// Generated by scripts/commonPasswords.mjs; do not edit. The ${lines.length.toLocaleString('en')} most common
// passwords, most common first, from SecLists (danielmiessler/SecLists,
// ${PATH}, commit ${COMMIT.slice(0, 7)}), MIT licence.
// A password that is exactly one of them is not allowed (commonRank).

export const COMMON_PASSWORDS_SOURCE = 'https://github.com/danielmiessler/SecLists/blob/${COMMIT}/${PATH}';

export const COMMON_PASSWORDS_TEXT = ${JSON.stringify(lines.join('\n'))};
`,
);
console.log(`wrote ${lines.length} passwords to ${OUT}`);
